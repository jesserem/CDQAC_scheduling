"""Standardized offline-RL episode format for real-world routing-type COP datasets.

Two levels, mirroring the FJSP datasets of the paper (one instance, several
behaviour sources replayed through the environment):

* an **instance** is the static problem a decision maker faced: the stops, the
  travel-time model, time windows, service and release times, zones;
* a **trajectory** is one sequence of decisions on an instance.  It is either
  *logged* in the real world (an Amazon driver's stop sequence, a Cainiao
  courier's completion order, with realized completion times when the log has
  them) or *synthetic* (random / nearest-neighbour / eps-greedy ... generated by
  :mod:`realworld.routing.behaviors`).  Many trajectories can share an instance.

Conventions (all datasets):

* node 0 of every instance is the depot / start location; it is never an
  action.  Nodes ``1 .. n_nodes-1`` are the stops, the rest is padding;
* times are **minutes** relative to the episode start (``clock = 0``);
  ``tw_end = inf`` means "no time window";
* coordinates are local planar **km** (x east, y north) with the depot at the
  origin (equirectangular projection, accurate at city scale);
* travel times come either from a per-instance matrix (``travel_mode ==
  "matrix"``, e.g. Amazon's historically-averaged times) or from
  ``detour * euclidean_km / speed`` (``travel_mode == "haversine"``, e.g. LaDe,
  whose logs have no travel times).

Everything is stored in a single ``.npz`` (plain arrays, ``allow_pickle`` not
needed) with a JSON string holding names and metadata.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence

import numpy as np

FORMAT_VERSION = 1

# Fields indexed by instance (first dimension E) and by trajectory (first dim K).
INSTANCE_ARRAYS = ("n_nodes", "coords", "node_feats", "zone", "zone2", "release",
                   "tw_start", "tw_end", "service", "speed", "start_tod", "inst_global")
TRAJ_ARRAYS = ("traj_inst", "traj_len", "traj_actions", "traj_times", "traj_source")


def latlng_to_local_km(lat: np.ndarray, lng: np.ndarray, lat0: float, lng0: float):
    """Equirectangular projection of WGS84 coordinates around (lat0, lng0), in km."""
    x = (np.asarray(lng, dtype=np.float64) - lng0) * 111.320 * np.cos(np.radians(lat0))
    y = (np.asarray(lat, dtype=np.float64) - lat0) * 110.574
    return x.astype(np.float32), y.astype(np.float32)


def haversine_km(lat1, lng1, lat2, lng2):
    """Great-circle distance in km (vectorized)."""
    lat1, lng1, lat2, lng2 = map(np.radians, (lat1, lng1, lat2, lng2))
    a = np.sin((lat2 - lat1) / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin((lng2 - lng1) / 2) ** 2
    return 2 * 6371.0088 * np.arcsin(np.sqrt(np.clip(a, 0.0, 1.0)))


@dataclass
class InstanceRecord:
    """One instance before padding; adapters build a list of these.

    Only ``coords`` is required; everything else has a neutral default.
    """
    coords: np.ndarray                      # [n, 2] local km, node 0 = depot
    node_feats: Optional[np.ndarray] = None  # [n, F] dataset-specific static features
    zone: Optional[np.ndarray] = None        # [n] int, -1 = none
    zone2: Optional[np.ndarray] = None       # [n] int, -1 = none
    release: Optional[np.ndarray] = None     # [n] minutes (0 = known at start)
    tw_start: Optional[np.ndarray] = None    # [n] minutes (0 if none)
    tw_end: Optional[np.ndarray] = None      # [n] minutes (inf if none)
    service: Optional[np.ndarray] = None     # [n] minutes
    travel: Optional[np.ndarray] = None      # [n, n] minutes (matrix mode)
    speed: float = 0.25                      # km / minute (haversine mode); 0.25 = 15 km/h
    start_tod: float = 0.0                   # local minutes of day at clock 0
    inst_global: Optional[np.ndarray] = None  # [G] dataset-specific instance features
    meta: Dict = field(default_factory=dict)


@dataclass
class TrajectoryRecord:
    inst: int                                # index into the instance list
    actions: np.ndarray                      # [T] node indices (no depot), visiting order
    times: Optional[np.ndarray] = None       # [T] completion times (minutes); None = not logged
    source: str = "logged"


@dataclass
class RoutingEpisodeSet:
    """Padded, array-based container for instances and trajectories (see module doc)."""
    name: str
    split: str
    travel_mode: str                          # "matrix" | "haversine"
    # instance arrays ------------------------------------------------------------
    n_nodes: np.ndarray                       # [E] int32
    coords: np.ndarray                        # [E, N, 2] float32
    node_feats: np.ndarray                    # [E, N, F] float32
    zone: np.ndarray                          # [E, N] int32
    zone2: np.ndarray                         # [E, N] int32
    release: np.ndarray                       # [E, N] float32
    tw_start: np.ndarray                      # [E, N] float32
    tw_end: np.ndarray                        # [E, N] float32 (inf = none)
    service: np.ndarray                       # [E, N] float32
    speed: np.ndarray                         # [E] float32 km/min
    start_tod: np.ndarray                     # [E] float32
    inst_global: np.ndarray                   # [E, G] float32
    travel_offsets: Optional[np.ndarray]      # [E] int64 (matrix mode)
    travel_flat: Optional[np.ndarray]         # [sum n^2] float32 (matrix mode)
    # trajectory arrays ----------------------------------------------------------
    traj_inst: np.ndarray                     # [K] int32
    traj_len: np.ndarray                      # [K] int32
    traj_actions: np.ndarray                  # [K, N-1] int32, -1 padded
    traj_times: np.ndarray                    # [K, N-1] float32, NaN = not logged
    traj_source: np.ndarray                   # [K] int16 index into source_names
    source_names: List[str]
    # names / metadata -----------------------------------------------------------
    node_feat_names: List[str]
    glob_feat_names: List[str]
    inst_meta: List[Dict]
    detour: float = 1.3                       # haversine mode: road / straight-line ratio
    meta: Dict = field(default_factory=dict)

    # ------------------------------------------------------------------ build
    @classmethod
    def from_records(cls, name: str, split: str, travel_mode: str,
                     instances: Sequence[InstanceRecord], trajectories: Sequence[TrajectoryRecord],
                     node_feat_names: Sequence[str] = (), glob_feat_names: Sequence[str] = (),
                     detour: float = 1.3, meta: Optional[Dict] = None,
                     max_nodes: Optional[int] = None) -> "RoutingEpisodeSet":
        if travel_mode not in ("matrix", "haversine"):
            raise ValueError(f"unknown travel_mode {travel_mode!r}")
        E = len(instances)
        if E == 0:
            raise ValueError("no instances")
        sizes = np.array([len(r.coords) for r in instances], dtype=np.int32)
        N = int(max_nodes or sizes.max())
        if sizes.max() > N:
            raise ValueError(f"instance with {sizes.max()} nodes exceeds max_nodes={N}")
        F = len(node_feat_names)
        G = len(glob_feat_names)

        coords = np.zeros((E, N, 2), np.float32)
        node_feats = np.zeros((E, N, F), np.float32)
        zone = np.full((E, N), -1, np.int32)
        zone2 = np.full((E, N), -1, np.int32)
        release = np.zeros((E, N), np.float32)
        tw_start = np.zeros((E, N), np.float32)
        tw_end = np.full((E, N), np.inf, np.float32)
        service = np.zeros((E, N), np.float32)
        speed = np.zeros(E, np.float32)
        start_tod = np.zeros(E, np.float32)
        inst_global = np.zeros((E, G), np.float32)
        offsets = np.zeros(E, np.int64) if travel_mode == "matrix" else None
        flat_parts = [] if travel_mode == "matrix" else None
        pos = 0
        for e, r in enumerate(instances):
            n = sizes[e]
            coords[e, :n] = r.coords
            if F:
                if r.node_feats is None or r.node_feats.shape != (n, F):
                    raise ValueError(f"instance {e}: node_feats must have shape {(n, F)}")
                node_feats[e, :n] = r.node_feats
            for arr, val in ((zone, r.zone), (zone2, r.zone2), (release, r.release),
                             (tw_start, r.tw_start), (tw_end, r.tw_end), (service, r.service)):
                if val is not None:
                    arr[e, :n] = val
            speed[e] = r.speed
            start_tod[e] = r.start_tod
            if G:
                inst_global[e] = r.inst_global
            if travel_mode == "matrix":
                if r.travel is None or r.travel.shape != (n, n):
                    raise ValueError(f"instance {e}: travel matrix must have shape {(n, n)}")
                offsets[e] = pos
                flat_parts.append(np.asarray(r.travel, np.float32).ravel())
                pos += n * n
        travel_flat = np.concatenate(flat_parts) if travel_mode == "matrix" else None

        ds = cls(name=name, split=split, travel_mode=travel_mode, n_nodes=sizes, coords=coords,
                 node_feats=node_feats, zone=zone, zone2=zone2, release=release, tw_start=tw_start,
                 tw_end=tw_end, service=service, speed=speed, start_tod=start_tod,
                 inst_global=inst_global, travel_offsets=offsets, travel_flat=travel_flat,
                 traj_inst=np.zeros(0, np.int32), traj_len=np.zeros(0, np.int32),
                 traj_actions=np.zeros((0, N - 1), np.int32),
                 traj_times=np.zeros((0, N - 1), np.float32),
                 traj_source=np.zeros(0, np.int16), source_names=[],
                 node_feat_names=list(node_feat_names), glob_feat_names=list(glob_feat_names),
                 inst_meta=[dict(r.meta) for r in instances], detour=detour, meta=dict(meta or {}))
        for t in trajectories:
            ds.add_trajectories([t.inst], [t.actions], t.source,
                                times=None if t.times is None else [t.times])
        return ds

    # --------------------------------------------------------------- basic info
    @property
    def num_instances(self) -> int:
        return int(self.n_nodes.shape[0])

    @property
    def num_trajectories(self) -> int:
        return int(self.traj_inst.shape[0])

    @property
    def max_nodes(self) -> int:
        return int(self.coords.shape[1])

    def travel_matrix(self, e: int) -> np.ndarray:
        """Dense [n, n] travel-time matrix (minutes) of instance ``e``."""
        n = int(self.n_nodes[e])
        if self.travel_mode == "matrix":
            o = int(self.travel_offsets[e])
            return self.travel_flat[o:o + n * n].reshape(n, n)
        xy = self.coords[e, :n].astype(np.float64)
        d = np.sqrt(((xy[:, None, :] - xy[None, :, :]) ** 2).sum(-1))
        return (self.detour * d / float(self.speed[e])).astype(np.float32)

    def source_id(self, source: str) -> int:
        if source not in self.source_names:
            self.source_names.append(source)
        return self.source_names.index(source)

    def trajectory_indices(self, sources: Optional[Sequence[str]] = None) -> np.ndarray:
        """Indices of trajectories whose source is in ``sources`` (all if None).

        A source name ending in ``*`` is a prefix match (``"eps_nn*"``).
        """
        if sources is None:
            return np.arange(self.num_trajectories)
        wanted = set()
        for s in sources:
            for i, name in enumerate(self.source_names):
                if name == s or (s.endswith("*") and name.startswith(s[:-1])):
                    wanted.add(i)
        return np.nonzero(np.isin(self.traj_source, list(wanted)))[0]

    # ---------------------------------------------------------- trajectories
    def add_trajectories(self, inst: Sequence[int], actions: Sequence[np.ndarray], source: str,
                         times: Optional[Sequence[Optional[np.ndarray]]] = None,
                         validate: bool = True) -> None:
        """Append trajectories (one per entry of ``inst``) generated by ``source``."""
        K = len(inst)
        if K == 0:
            return
        N = self.max_nodes
        acts = np.full((K, N - 1), -1, np.int32)
        tms = np.full((K, N - 1), np.nan, np.float32)
        lens = np.zeros(K, np.int32)
        for k in range(K):
            a = np.asarray(actions[k], dtype=np.int64)
            e = int(inst[k])
            if validate:
                n = int(self.n_nodes[e])
                if len(a) != n - 1 or set(a.tolist()) != set(range(1, n)):
                    raise ValueError(f"trajectory {k} on instance {e} is not a permutation of 1..{n - 1}")
            acts[k, :len(a)] = a
            lens[k] = len(a)
            if times is not None and times[k] is not None:
                tms[k, :len(a)] = np.asarray(times[k], np.float32)
        sid = self.source_id(source)
        self.traj_inst = np.concatenate([self.traj_inst, np.asarray(inst, np.int32)])
        self.traj_len = np.concatenate([self.traj_len, lens])
        self.traj_actions = np.concatenate([self.traj_actions, acts])
        self.traj_times = np.concatenate([self.traj_times, tms])
        self.traj_source = np.concatenate([self.traj_source, np.full(K, sid, np.int16)])

    def remove_sources(self, sources: Sequence[str]) -> None:
        drop = self.trajectory_indices(sources)
        keep = np.setdiff1d(np.arange(self.num_trajectories), drop)
        for f in TRAJ_ARRAYS:
            setattr(self, f, getattr(self, f)[keep])

    # ------------------------------------------------------------- selection
    def select_instances(self, idx: Sequence[int], split: Optional[str] = None) -> "RoutingEpisodeSet":
        """New set with instances ``idx`` (re-indexed) and all their trajectories."""
        idx = np.asarray(idx, dtype=np.int64)
        remap = np.full(self.num_instances, -1, np.int64)
        remap[idx] = np.arange(len(idx))
        kept_traj = np.nonzero(remap[self.traj_inst] >= 0)[0]
        kw = {f: getattr(self, f)[idx] for f in INSTANCE_ARRAYS}
        if self.travel_mode == "matrix":
            sizes = self.n_nodes[idx].astype(np.int64) ** 2
            offsets = np.concatenate([[0], np.cumsum(sizes)[:-1]]).astype(np.int64)
            parts = [self.travel_flat[self.travel_offsets[e]:self.travel_offsets[e] + s]
                     for e, s in zip(idx, sizes)]
            kw["travel_offsets"] = offsets
            kw["travel_flat"] = np.concatenate(parts) if parts else np.zeros(0, np.float32)
        else:
            kw["travel_offsets"] = None
            kw["travel_flat"] = None
        return RoutingEpisodeSet(
            name=self.name, split=split or self.split, travel_mode=self.travel_mode, **kw,
            traj_inst=remap[self.traj_inst[kept_traj]].astype(np.int32),
            traj_len=self.traj_len[kept_traj], traj_actions=self.traj_actions[kept_traj],
            traj_times=self.traj_times[kept_traj], traj_source=self.traj_source[kept_traj],
            source_names=list(self.source_names), node_feat_names=list(self.node_feat_names),
            glob_feat_names=list(self.glob_feat_names),
            inst_meta=[self.inst_meta[i] for i in idx], detour=self.detour, meta=dict(self.meta))

    def split_by(self, fractions: Dict[str, float], seed: int = 0,
                 group_key: Optional[str] = None) -> Dict[str, "RoutingEpisodeSet"]:
        """Random split of instances into named parts (fractions sum to 1).

        With ``group_key`` whole groups (e.g. all routes of one station or all
        episodes of one day) go to the same part, avoiding leakage.
        """
        rng = np.random.default_rng(seed)
        if group_key is None:
            groups = np.arange(self.num_instances)
            units = rng.permutation(self.num_instances)
        else:
            keys = [str(m.get(group_key)) for m in self.inst_meta]
            uniq = sorted(set(keys))
            order = rng.permutation(len(uniq))
            rank = {uniq[i]: r for r, i in enumerate(order)}
            groups = np.array([rank[k] for k in keys])
            units = np.arange(len(uniq))
        names = list(fractions)
        cuts = np.cumsum([fractions[n] for n in names])
        cuts = np.round(cuts / cuts[-1] * len(units)).astype(int)
        out, start = {}, 0
        for name, stop in zip(names, cuts):
            chosen_units = units[start:stop]
            if group_key is None:
                idx = np.sort(chosen_units)
            else:
                idx = np.nonzero(np.isin(groups, chosen_units))[0]
            out[name] = self.select_instances(idx, split=name)
            start = stop
        return out

    # ---------------------------------------------------------- persistence
    def save(self, path: str) -> str:
        if not path.endswith(".npz"):
            path += ".npz"
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        header = dict(format_version=FORMAT_VERSION, name=self.name, split=self.split,
                      travel_mode=self.travel_mode, detour=self.detour,
                      source_names=self.source_names, node_feat_names=self.node_feat_names,
                      glob_feat_names=self.glob_feat_names, inst_meta=self.inst_meta,
                      meta=self.meta)
        arrays = {f: getattr(self, f) for f in INSTANCE_ARRAYS + TRAJ_ARRAYS}
        if self.travel_mode == "matrix":
            arrays["travel_offsets"] = self.travel_offsets
            arrays["travel_flat"] = self.travel_flat
        arrays["__header__"] = np.array(json.dumps(header, default=_json_default))
        np.savez_compressed(path, **arrays)
        return path

    @classmethod
    def load(cls, path: str) -> "RoutingEpisodeSet":
        with np.load(path, allow_pickle=False) as z:
            header = json.loads(str(z["__header__"]))
            if header.get("format_version", 0) > FORMAT_VERSION:
                raise ValueError(f"{path} was written by a newer format version")
            kw = {f: z[f] for f in INSTANCE_ARRAYS + TRAJ_ARRAYS}
            matrix = header["travel_mode"] == "matrix"
            kw["travel_offsets"] = z["travel_offsets"] if matrix else None
            kw["travel_flat"] = z["travel_flat"] if matrix else None
        return cls(name=header["name"], split=header["split"], travel_mode=header["travel_mode"],
                   source_names=header["source_names"], node_feat_names=header["node_feat_names"],
                   glob_feat_names=header["glob_feat_names"], inst_meta=header["inst_meta"],
                   detour=header.get("detour", 1.3), meta=header.get("meta", {}), **kw)

    # ------------------------------------------------------------- summary
    def summary(self) -> Dict:
        """Datasheet-style statistics (sizes, sources, trajectories per instance)."""
        per_source = {name: int((self.traj_source == i).sum()) for i, name in enumerate(self.source_names)}
        n_stops = self.n_nodes - 1
        dynamic = float(np.mean([(self.release[e, 1:n] > 0).any()
                                 for e, n in enumerate(self.n_nodes)])) if self.num_instances else 0.0
        has_tw = np.isfinite(self.tw_end) & (np.arange(self.max_nodes)[None, :] < self.n_nodes[:, None])
        return dict(name=self.name, split=self.split, travel_mode=self.travel_mode,
                    instances=self.num_instances, trajectories=self.num_trajectories,
                    trajectories_per_source=per_source,
                    stops_mean=float(n_stops.mean()), stops_min=int(n_stops.min()),
                    stops_max=int(n_stops.max()),
                    frac_instances_dynamic=dynamic,
                    frac_stops_with_tw=float(has_tw[:, 1:].sum() / max(1, n_stops.sum())),
                    logged_times=bool(np.isfinite(self.traj_times).any()))


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return None if not np.isfinite(o) else float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    return str(o)


def concat_sets(sets: Sequence[RoutingEpisodeSet], split: Optional[str] = None) -> RoutingEpisodeSet:
    """Concatenate episode sets of the same dataset (e.g. several LaDe cities)."""
    if len(sets) == 1:
        return sets[0]
    base = sets[0]
    for s in sets[1:]:
        if (s.travel_mode != base.travel_mode or s.node_feat_names != base.node_feat_names
                or s.glob_feat_names != base.glob_feat_names):
            raise ValueError("cannot concatenate episode sets with different layouts")
    N = max(s.max_nodes for s in sets)

    def pad(a, fill, n_axis=1):
        if a.shape[n_axis] == N:
            return a
        width = [(0, 0)] * a.ndim
        width[n_axis] = (0, N - a.shape[n_axis])
        return np.pad(a, width, constant_values=fill)

    fills = dict(coords=0.0, node_feats=0.0, zone=-1, zone2=-1, release=0.0, tw_start=0.0,
                 tw_end=np.inf, service=0.0)
    kw = {}
    for f in INSTANCE_ARRAYS:
        parts = [getattr(s, f) for s in sets]
        if f in fills:
            parts = [pad(p, fills[f]) for p in parts]
        kw[f] = np.concatenate(parts)
    if base.travel_mode == "matrix":
        offs, pos = [], 0
        for s in sets:
            offs.append(s.travel_offsets + pos)
            pos += len(s.travel_flat)
        kw["travel_offsets"] = np.concatenate(offs)
        kw["travel_flat"] = np.concatenate([s.travel_flat for s in sets])
    else:
        kw["travel_offsets"] = None
        kw["travel_flat"] = None
    names = []
    for s in sets:
        for n in s.source_names:
            if n not in names:
                names.append(n)
    inst_off = np.cumsum([0] + [s.num_instances for s in sets[:-1]])
    traj_inst = np.concatenate([s.traj_inst + o for s, o in zip(sets, inst_off)]).astype(np.int32)
    traj_source = np.concatenate([np.array([names.index(s.source_names[i]) for i in s.traj_source],
                                           dtype=np.int16) for s in sets])
    traj_actions = np.concatenate([np.pad(s.traj_actions, ((0, 0), (0, N - 1 - s.traj_actions.shape[1])),
                                          constant_values=-1) for s in sets])
    traj_times = np.concatenate([np.pad(s.traj_times, ((0, 0), (0, N - 1 - s.traj_times.shape[1])),
                                        constant_values=np.nan) for s in sets])
    meta = dict(base.meta)
    meta["concatenated_from"] = [s.meta.get("part", s.split) for s in sets]
    return RoutingEpisodeSet(
        name=base.name, split=split or base.split, travel_mode=base.travel_mode, **kw,
        traj_inst=traj_inst, traj_len=np.concatenate([s.traj_len for s in sets]),
        traj_actions=traj_actions, traj_times=traj_times, traj_source=traj_source, source_names=names,
        node_feat_names=list(base.node_feat_names), glob_feat_names=list(base.glob_feat_names),
        inst_meta=[m for s in sets for m in s.inst_meta], detour=base.detour, meta=meta)
